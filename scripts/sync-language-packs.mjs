/**
 * Generates VShoon's built-in language pack extensions from a pinned `vscode-loc` checkout.
 *
 * The translations are Microsoft's, MIT licensed, and released on their own schedule, so they are
 * treated like the core: pinned in `vshoon.lock.json`, fetched on demand, never committed. The
 * generated extension is a plain language pack — a manifest plus JSON — so it needs no compilation
 * step and is picked up by the build like any other built-in extension.
 */

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fail, git, readLock, repoRoot } from './core-paths.mjs';

const TRANSLATION_SUFFIX = '.i18n.json';

const lock = readLock();
const config = lock.languagePacks;
const cacheDir = join(repoRoot, '.i18n');

if (!config?.languages?.length) {
	console.log('[vshoon] no language packs are pinned');
} else {
	fetchTranslations();
	for (const language of config.languages) {
		generateExtension(language);
	}
}

/** Fetches only the pinned commit, and only the language directories that are actually used. */
function fetchTranslations() {
	if (!existsSync(join(cacheDir, '.git'))) {
		console.log(`[vshoon] creating translation checkout at ${cacheDir}`);
		mkdirSync(cacheDir, { recursive: true });
		git(['init', '--quiet'], { cwd: cacheDir });
		git(['remote', 'add', 'origin', config.repository], { cwd: cacheDir });

		// The same reason the core pins these: Git for Windows would otherwise hand back CRLF
		// translations and the generated extension would differ per platform.
		git(['config', 'core.autocrlf', 'false'], { cwd: cacheDir });
		git(['config', 'core.eol', 'lf'], { cwd: cacheDir });
	}

	git(['remote', 'set-url', 'origin', config.repository], { cwd: cacheDir });

	if (!hasPinnedCommit()) {
		console.log(`[vshoon] fetching translations @ ${config.commit.slice(0, 10)}`);
		git(['fetch', '--depth', '1', '--filter=blob:none', 'origin', config.commit], { cwd: cacheDir });
	}

	git(['sparse-checkout', 'set', ...config.languages.map(language => language.source)], { cwd: cacheDir });
	git(['checkout', '--force', '--detach', config.commit], { cwd: cacheDir });
}

function hasPinnedCommit() {
	try {
		return git(['cat-file', '-t', config.commit], { cwd: cacheDir, capture: true, silent: true }).trim() === 'commit';
	} catch {
		return false;
	}
}

/**
 * Writes one language pack extension.
 *
 * The manifest is generated rather than committed because its `translations` list has to name
 * every file the pack ends up carrying; a hand-written list silently rots into missing
 * translations the next time the pinned commit moves.
 */
function generateExtension({ id, source, extension }) {
	const from = join(cacheDir, source);
	if (!existsSync(from)) {
		fail(`${source} is not part of ${config.repository} at ${config.commit.slice(0, 10)}.`);
	}

	const upstream = JSON.parse(readFileSync(join(from, 'package.json'), 'utf8'));
	const localization = upstream.contributes?.localizations?.find(entry => entry.languageId === id);
	if (!localization) {
		fail(`${source} does not contribute a localization for "${id}".`);
	}

	const target = join(repoRoot, extension);
	rmSync(target, { recursive: true, force: true });
	mkdirSync(target, { recursive: true });
	cpSync(join(from, 'translations'), join(target, 'translations'), { recursive: true });
	cpSync(join(cacheDir, 'LICENSE.md'), join(target, 'LICENSE.md'));
	const ownStrings = mergeVShoonStrings(id, join(target, 'translations', 'main.i18n.json'));
	const ownExtensions = copyVShoonExtensionStrings(id, target);

	const manifest = {
		name: extension.split('/').pop(),
		displayName: `${localization.languageName} Language Pack`,
		description: `${localization.languageName} language pack for VShoon.`,
		version: upstream.version,
		publisher: 'vshoon',
		license: 'MIT',
		engines: { vscode: `^${lock.upstream.version}` },
		categories: ['Language Packs'],
		contributes: {
			localizations: [{
				languageId: id,
				languageName: localization.languageName,
				localizedLanguageName: localization.localizedLanguageName,
				translations: collectTranslations(target)
			}]
		}
	};

	writeFileSync(join(target, 'package.json'), `${JSON.stringify(manifest, undefined, '\t')}\n`, 'utf8');
	writeFileSync(join(target, 'README.md'), [
		`# ${manifest.displayName}`,
		'',
		'Generated by `npm run sync:i18n`. Do not edit by hand: the next sync overwrites this directory.',
		'',
		`- Source: ${config.repository}`,
		`- Commit: ${config.commit}`,
		`- Upstream pack version: ${upstream.version}`,
		'',
		'The translations are Microsoft\'s, under the MIT license kept in `LICENSE.md`.',
		''
	].join('\n'), 'utf8');

	console.log(`[vshoon] generated ${extension} (${manifest.contributes.localizations[0].translations.length} translation files, ${ownStrings} VShoon strings, ${ownExtensions} VShoon extension manifests)`);
}

/**
 * Adds VShoon's own translations to the pack.
 *
 * No upstream language pack carries strings from `vs/vshoon`, so without this the product's own
 * surfaces — the launcher above all — stay English inside an otherwise translated workbench. The
 * strings are merged into the pack's main file, keyed by module exactly as upstream keys its own.
 */
function mergeVShoonStrings(language, mainTranslationFile) {
	const ownFile = join(repoRoot, 'i18n', language, 'vshoon.i18n.json');
	if (!existsSync(ownFile)) {
		return 0;
	}

	const own = JSON.parse(readFileSync(ownFile, 'utf8'));
	const main = JSON.parse(readFileSync(mainTranslationFile, 'utf8'));
	let merged = 0;

	for (const [moduleId, strings] of Object.entries(own.contents ?? {})) {
		main.contents[moduleId] = { ...main.contents[moduleId], ...strings };
		merged += Object.keys(strings).length;
	}

	writeFileSync(mainTranslationFile, JSON.stringify(main, undefined, '	'), 'utf8');

	return merged;
}

/**
 * Adds VShoon's own extension manifests to the pack.
 *
 * A `%key%` in a built-in manifest is resolved from the pack when it carries a bundle named after
 * the extension's translation id, and from the extension's own `package.nls.json` otherwise. So
 * without this a Korean workbench would show VShoon's settings in English while every upstream
 * extension around them is translated.
 */
function copyVShoonExtensionStrings(language, target) {
	const ownDir = join(repoRoot, 'i18n', language, 'extensions');
	if (!existsSync(ownDir)) {
		return 0;
	}

	const extensionsDir = join(target, 'translations', 'extensions');
	mkdirSync(extensionsDir, { recursive: true });
	const bundles = readdirSync(ownDir).filter(entry => entry.endsWith(TRANSLATION_SUFFIX)).sort();

	for (const bundle of bundles) {
		const destination = join(extensionsDir, bundle);
		if (existsSync(destination)) {
			fail(`${bundle} is already translated by ${config.repository}; remove i18n/${language}/extensions/${bundle}.`);
		}

		cpSync(join(ownDir, bundle), destination);
	}

	return bundles.length;
}

/**
 * Names every translation file the generated pack carries: `main.i18n.json` is the workbench
 * itself, and each file under `translations/extensions` is named by the extension it translates.
 */
function collectTranslations(source) {
	const translations = [{ id: 'vscode', path: './translations/main.i18n.json' }];
	const extensionsDir = join(source, 'translations', 'extensions');
	if (!existsSync(extensionsDir)) {
		return translations;
	}

	for (const file of readdirSync(extensionsDir).filter(entry => entry.endsWith(TRANSLATION_SUFFIX)).sort()) {
		translations.push({
			id: file.slice(0, -TRANSLATION_SUFFIX.length),
			path: `./translations/extensions/${file}`
		});
	}

	return translations;
}
